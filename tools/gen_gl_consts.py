#!/usr/bin/env python3
"""Generate WebGL constant table (src/js/glconst.js) from the GLES2 header."""
import re, sys
hdr = open(sys.argv[1]).read()
out = {}
for name, val in re.findall(r'#define GL_([A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|\d+)\b', hdr):
    out.setdefault(name, int(val, 0))
# WebGL-only constants
out.update(UNPACK_FLIP_Y_WEBGL=0x9240, UNPACK_PREMULTIPLY_ALPHA_WEBGL=0x9241,
           CONTEXT_LOST_WEBGL=0x9242, UNPACK_COLORSPACE_CONVERSION_WEBGL=0x9243,
           BROWSER_DEFAULT_WEBGL=0x9244, DEPTH_STENCIL=0x84F9,
           DEPTH_STENCIL_ATTACHMENT=0x821A)
for k in ('ES_VERSION_2_0',): out.pop(k, None)
lines = ',\n'.join('  %s: %d' % (k, v) for k, v in sorted(out.items()))
open(sys.argv[2], 'w').write('// generated by tools/gen_gl_consts.py\nvar __GL_CONSTS = {\n' + lines + '\n};\n')
print(len(out), 'constants')
